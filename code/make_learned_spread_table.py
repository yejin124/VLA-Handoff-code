"""Supplementary table: supervised readout of action spread against the handoff readout (learned_spread_contrast.py).

Usage: python code/make_learned_spread_table.py data/learned_spread_20261109/confirm_results.json paper/tables
"""
import json
import sys
from pathlib import Path

ROWS = [('gr00t_bridge_confirm', 'Bridge', (10, 20)), ('gr00t_spatial_confirm', 'LIBERO-Spatial', (40, 80))]
PRIMARY = {('gr00t_bridge_confirm', 20), ('gr00t_spatial_confirm', 80)}


def ci(v, p=False):
    lo, hi = v['ci95']
    s = f"${v['estimate']:+.3f}$ [${lo:+.3f}$, ${hi:+.3f}$]"
    return s + (f" ({v['one_sided_p']:.4f})" if p else '')


def main():
    cells = json.loads(Path(sys.argv[1]).read_text())['cells']
    out = [r'% generated by code/make_learned_spread_table.py; do not edit', r'\begin{tabular}{@{}llcccccll@{}}', r'\toprule',
           r'Cohort & Step & Spread & Learned spread & Handoff & Scene + learned & Scene + handoff & '
           r'Handoff $-$ learned [95\% CI] ($p$) & Learned $-$ spread [95\% CI]\\', r'\midrule']
    for key, name, steps in ROWS:
        for st in steps:
            c = cells[f'{key}|{st}']
            m, k = c['methods'], c['contrasts']
            mark = r'$^\dagger$' if (key, st) in PRIMARY else ''
            out.append(f"{name}{mark} & {st} & {m['Spread']['estimate']:.3f} & {m['S']['estimate']:.3f} & {m['H']['estimate']:.3f} & "
                       f"{m['GS']['estimate']:.3f} & {m['GH']['estimate']:.3f} & {ci(k['H-S'], p=True)} & {ci(k['S-Spread'])}\\\\")
    out += [r'\bottomrule', r'\end{tabular}']
    (Path(sys.argv[2]) / 'supp_learned_spread.tex').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
