"""Table of experiment 1 (input-level injection) from data/injection/exp1_input_level.json.

Usage: python code/make_injection_table.py data/injection/exp1_input_level.json paper/tables/input_injection.tex
"""
import json
import sys
from pathlib import Path

NAMES = {'gr00t': 'GR00T', 'molmoact': 'MolmoAct2', 'pi05': r'$\pi_{0.5}$'}


def fmt(v):
    interval = v.get('rho_ci95')
    if interval is None or v.get('mean_rho') is None:
        cell = '--'
    else:
        lo, hi = interval
        cell = f"${v['mean_rho']:+.2f}$ [${lo:+.2f}$, ${hi:+.2f}$]"
        if lo <= 0:
            cell = r'{\boldmath ' + cell + '}'
    def signed(value):
        return '--' if value is None else f'${value:+.2f}$'
    probability = '--' if v.get('sign_p_one_sided') is None or v.get('holm_p') is None else f"{v['holm_p']:.2f}"
    return (f"{cell} & {v['tasks_rho_positive']}/{v['tasks_with_rho']} & "
            f"{probability} & {signed(v.get('mean_dR_std'))} & {signed(v.get('mean_dS_std'))}")


def main():
    cells = json.loads(Path(sys.argv[1]).read_text())['cells']
    lines = [r'% generated by code/make_injection_table.py from data/injection/exp1_input_level.json; do not edit',
             r'\begin{tabular}{@{}lllccccc@{}}', r'\toprule',
             r'Suite & Policy & Cond. & $\rho(\Delta U_2,\Delta U_1)$ [95\% CI] & $\rho>0$ & Holm $p$ & $\Delta U_2$ & $\Delta U_1$\\',
             r'\midrule']
    for suite in ('spatial', 'object'):
        for policy in ('gr00t', 'molmoact', 'pi05'):
            for cond, label in (('occluder', 'Occ.'), ('moved', 'Goal')):
                lines.append(f"{suite.capitalize()} & {NAMES[policy]} & {label} & {fmt(cells[f'{policy}|{suite}|{cond}'])}\\\\")
    lines += [r'\bottomrule', r'\end{tabular}']
    output = Path(sys.argv[2])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
