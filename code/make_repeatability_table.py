"""Regenerate Table S9 from the archived, hash-verified sampling summaries.

This formats existing results; it does not rerun the GPU draws or bootstrap.
Usage: python code/make_repeatability_table.py DATA_DIR OUTPUT_TEX
"""
import argparse
import hashlib
import json
from pathlib import Path


POLICIES = (
    ("molmoact", "MolmoAct2 / Spatial"),
    ("pi05", r"$\pi_{0.5}$ / Spatial"),
    ("gr00t", "GR00T-N1.7 / Object"),
)


def load_verified(data_dir):
    manifest = json.loads((data_dir / "manifest.json").read_text())
    results = {}
    for model, _ in POLICIES:
        pair = {}
        for suffix in ("analysis", "final_audit"):
            name = f"{model}_{suffix}.json"
            payload = (data_dir / name).read_bytes()
            digest = hashlib.sha256(payload).hexdigest()
            if digest != manifest["files"][name]["sha256"]:
                raise ValueError(f"Archive checksum mismatch: {name}")
            pair[suffix] = json.loads(payload)
        analysis, audit = pair["analysis"], pair["final_audit"]
        if not (analysis["complete"] and audit["complete"] and audit["passed"]):
            raise ValueError(f"Incomplete or failed sampling audit: {model}")
        if analysis["final_audit_sha256"] != manifest["files"][f"{model}_final_audit.json"]["sha256"]:
            raise ValueError(f"Analysis/audit mismatch: {model}")
        if not (analysis["n_observations"] == analysis["archive_prefix_exact_count"]
                == audit["n_observations"] == audit["archive_prefix_exact_count"]):
            raise ValueError(f"Archived action prefix mismatch: {model}")
        results[model] = analysis
    return results


def make_table(results):
    lines = [
        "% generated by code/make_repeatability_table.py from archived 2026-10-14 summaries; raw action draws external",
        r"\begin{tabular}{@{}llrrr@{\hspace{2em}}r@{}}\toprule",
        r"Policy / suite & Condition & $n$ & $\rho$, $J=8$ [90\% CI] & $\rho$, $J=64$ [90\% CI] & MAE, $J=8\to64$\\\midrule",
    ]
    for model, label in POLICIES:
        for condition in ("occluder", "moved"):
            rows = {}
            for j in (8, 64):
                matches = [s for s in results[model]["summaries"]
                           if s["condition"] == condition
                           and s["comparison"] == "independent_seed_same_J" and s["J"] == j]
                if len(matches) != 1:
                    raise ValueError(f"Expected one summary for {model}/{condition}/J={j}")
                rows[j] = matches[0]
            if rows[8]["n"] != rows[64]["n"]:
                raise ValueError(f"Unpaired sample sizes: {model}/{condition}")
            corr = []
            for j in (8, 64):
                rho = rows[j]["spearman"]
                lo, hi = rho["ci90"]
                corr.append(f"{rho['estimate']:.3f} [{lo:.3f}, {hi:.3f}]")
            mae8 = rows[8]["mean_absolute_difference"]["estimate"]
            mae64 = rows[64]["mean_absolute_difference"]["estimate"]
            lines.append(f"{label} & {condition.capitalize()} & {rows[8]['n']} & "
                         f"{corr[0]} & {corr[1]} & {mae8:.5f}$\\to${mae64:.5f}" + r"\\")
    lines.append(r"\bottomrule\end{tabular}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data_dir", type=Path)
    parser.add_argument("output_tex", type=Path)
    args = parser.parse_args()
    results = load_verified(args.data_dir)
    args.output_tex.write_text(make_table(results))
    print(f"Wrote {args.output_tex}: 117 fixed observations, six policy-condition rows")


if __name__ == "__main__":
    main()
