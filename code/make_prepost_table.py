"""Supplementary tables for the pre/post-interface readouts (docs/PROTOCOLS.md).

Usage: python code/make_prepost_table.py <main_results.json> <tables_dir> [name=<variant_results.json> ...]
Writes supp_prepost.tex (readouts and contrasts per cell) and, with variants, supp_prepost_sensitivity.tex.
"""
import json
import sys
from pathlib import Path

CELLS = [('gr00t_bridge_confirm|20', 'Bridge, 20'), ('gr00t_spatial_confirm|80', 'LIBERO-Spatial, 80')]


def fmt(v, signed=True):
    return f'${v:+.3f}$' if signed else f'{v:.3f}'


def ci(c):
    lo, hi = c['ci95']
    return f"{fmt(c['estimate'])} [{fmt(lo)}, {fmt(hi)}]"


def main(main_path, out_dir, variants):
    res = json.loads(Path(main_path).read_text())
    rows = []
    for key, label in CELLS:
        c = res['cells'][key]
        m, k = c['methods'], c['contrasts']
        holm = res['prepost']['P-H'][key]['holm_p']
        rows.append(f"{label} & {fmt(m['P']['estimate'], False)} & {fmt(m['M']['estimate'], False)} & {fmt(m['H']['estimate'], False)} & "
                    f"{fmt(m['Spread']['estimate'], False)} & {ci(k['P-H'])} ({k['P-H']['one_sided_p']:.3f}; {holm:.3f}) & {ci(k['M-H'])} & "
                    f"{ci(k['P-M'])} & {ci(k['GP-GH'])} & {ci(k['P-G'])}\\\\")
    out = ['% generated by code/make_prepost_table.py; do not edit', r'\begin{tabular}{@{}lccccllll l@{}}', r'\toprule',
           r'Cohort, step & PRE & MID & POST & Spread & PRE $-$ POST [95\% CI] ($p$; Holm) & MID $-$ POST & PRE $-$ MID & '
           r'Scene + PRE $-$ Scene + POST & PRE $-$ Scene\\', r'\midrule', *rows, r'\bottomrule', r'\end{tabular}']
    (Path(out_dir) / 'supp_prepost.tex').write_text('\n'.join(out) + '\n')
    if variants:
        rows = []
        for name, path in variants:
            r = json.loads(Path(path).read_text())
            cells = ' & '.join(ci(r['cells'][key]['contrasts']['P-H']) + f" ({r['cells'][key]['contrasts']['P-H']['one_sided_p']:.3f})"
                               for key, _ in CELLS)
            rows.append(f'{name} & {cells}\\\\')
        out = ['% generated by code/make_prepost_table.py; do not edit', r'\begin{tabular}{@{}lll@{}}', r'\toprule',
               r'Readout setting & PRE $-$ POST, Bridge 20 [95\% CI] ($p$) & PRE $-$ POST, LIBERO-Spatial 80 [95\% CI] ($p$)\\', r'\midrule',
               *rows, r'\bottomrule', r'\end{tabular}']
        (Path(out_dir) / 'supp_prepost_sensitivity.tex').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], [v.rsplit('=', 1) for v in sys.argv[3:]])
