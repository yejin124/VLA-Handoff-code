"""Select readable supplementary tables from the detailed generated TeX exports.

Run the analysis formatters first, then:
    python code/make_compact_supp_tables.py paper/tables paper/tables

This is a presentation pass: numerical cells are copied verbatim. Selection is
by protocol (goal decoding; step-80 re-query), never by significance or effect.
Detailed exports are retained alongside the compact tables.
"""
import argparse
from pathlib import Path
import re

PI = r'$\pi_{0.5}$'
TAU = r'$\tau_0$'
SUITES = ('Spatial', 'Object')
GOALS = ('Moved goal', 'Relocated goal')
CONFIRM = {(cohort, step) for cohort, steps in (
    ('Bridge (all)', ('10', '20')), ('Bridge (new only)', ('10', '20')),
    ('Spatial', ('40', '80')), ('Object', ('40', '80'))) for step in steps}
IMAGE_CONTROL = {key for key in CONFIRM if key[0] in ('Bridge (all)', 'Spatial')}


def rows(path: Path, columns: int) -> list[list[str]]:
    """Read data rows in the simple tabular dialect emitted by our formatters."""
    result = []
    active = False
    for line in path.read_text().splitlines():
        if line.strip() == r'\midrule':
            active = True
        if not active or ' & ' not in line:
            continue
        values = [value.strip() for value in line.strip().removesuffix(r'\\').split(' & ')]
        if len(values) != columns:
            # Multi-column pooled summaries are not ordinary data rows.
            if r'\multicolumn' in line:
                continue
            raise ValueError(f'{path.name}: expected {columns} columns, got {len(values)}')
        result.append(values)
    if not result:
        raise ValueError(f'{path.name}: no data rows')
    return result


def table(columns: str, heading: list[str], body: list[list[str] | str]) -> str:
    lines = [r'% generated by code/make_compact_supp_tables.py; numerical cells copied unchanged',
             r'\begin{tabular}{@{}' + columns + r'@{}}', r'\toprule',
             ' & '.join(heading) + r'\\', r'\midrule']
    for row in body:
        lines.append(row if isinstance(row, str) else ' & '.join(row) + r'\\')
    return '\n'.join(lines + [r'\bottomrule', r'\end{tabular}', ''])


def unique(values: list[list[str]], indices: tuple[int, ...], expected: set[tuple[str, ...]]) -> None:
    keys = [tuple(clean_cohort(row[index]).replace('GR00T-N1.7', 'GR00T')
                  for index in indices) for row in values]
    if len(keys) != len(expected) or set(keys) != expected:
        raise ValueError(f'Expected {len(expected)} distinct protocol cells; '
                         f'missing={expected - set(keys)}, unexpected={set(keys) - expected}')


def clean_cohort(value: str) -> str:
    return value.replace(r'$^\dagger$', '').replace('LIBERO-', '')


def render(source: Path, destination: Path) -> None:
    """Preflight all inputs, then write five compact, result-preserving tables."""
    output = {}
    image = [r for r in rows(source / 'supp_image_encoders.tex', 9)
             if r[0] == 'A' and r[2] in ('Moved goal', 'Relocated goal')]
    unique(image, (1, 2, 3), {(s, g, p) for s in SUITES for g in GOALS
                            for p in (PI, 'GR00T', 'MolmoAct2')})
    image_body = [[r[1], r[2].replace(' goal', ''), r[3], r[4], r[6].split(' (')[0], r[7], r[8]]
                  for r in image]
    output['supp_goal_summary.tex'] = table('lllcccc',
        ['Suite', 'Goal', 'Policy', 'Handoff', 'DINOv2', 'ResNet',
         r'\shortstack{Handoff $-$ DINOv2\\95\% CI}'], image_body)

    cells = rows(source / 'supp_confirm_cells.tex', 7)
    unique(cells, (0, 1), CONFIRM)
    images = rows(source / 'supp_confirm_image.tex', 5)
    unique(images, (0, 1), IMAGE_CONTROL)
    image_map = {(clean_cohort(r[0]), r[1]): r[4] for r in images}
    body = [[clean_cohort(r[0]), r[1], r[6], image_map.get((clean_cohort(r[0]), r[1]), '--')]
            for r in cells]
    output['supp_confirm_summary.tex'] = table('llcc',
        ['Cohort', 'Step', r'\shortstack{Beyond scene\\Difference [95\% CI]}',
         r'\shortstack{Beyond scene + DINOv2\\Difference [95\% CI]}'], body)

    policies = rows(source / 'supp_confirm_policies.tex', 11)
    unique(policies, (0, 1, 2), {(p, s, step) for p in (PI, 'GR00T', 'MolmoAct2', TAU, 'SmolVLA')
                               for s in SUITES for step in ('40', '80')
                               if (p, s, step) != ('GR00T', 'Spatial', '80')})
    body, last = [], None
    for r in policies:
        if r[2] != last:
            if last is not None:
                body.append(r'\midrule')
            desc = 'primary landmark; Holm-adjusted' if r[2] == '80' else 'secondary landmark; unadjusted'
            body.append(r'\multicolumn{6}{l}{\textbf{Step ' + r[2] + '} (' + desc + r' $p$)}\\')
            last = r[2]
        body.append([r[0], r[1], *r[7:11]])
    output['supp_policy_summary.tex'] = table('llcccc',
        ['Policy', 'Suite', r'$\Delta_{\rm handoff}$ [95\% CI]', '$p$',
         r'$\Delta_{\rm gap}$ [95\% CI]', '$p$'], body)

    requery = [r for r in rows(source / 'supp_requery.tex', 10) if r[2] == '80']
    unique(requery, (0, 1), {(p, c) for p in (PI, 'MolmoAct2') for c in ('Occluder', *GOALS)})
    output['supp_requery_summary.tex'] = table('llcccc',
        ['Policy', 'Condition', r'\shortstack{Fail/$N$\\(tasks)}', 'Prefix spread', 'Handoff', 'STAC-style MMD'],
        [[r[0], r[1], r[3], r[4], r[6], r[8]] for r in requery])

    # Keep all 12 J64 tests, including both seed streams and their Holm p-values.
    path = source / 'supp_sampling_primary.tex'
    sampling = rows(path, 5)
    if len(sampling) != 12:
        raise ValueError('Expected all 12 primary sampling comparisons')
    body, index, identities, cohort = [], 0, [], None
    comparison = {'Scene + handoff minus raw spread': r'$(G+H)-s$',
                  'Handoff minus learned spread': r'$H-S$'}
    for line in path.read_text().splitlines():
        if line.startswith(r'\multicolumn{5}'):
            match = re.search(r'\\textbf\{([^}]+)\}', line)
            if not match:
                raise ValueError('Missing sampling cohort label')
            cohort = match.group(1)
            if body:
                body.append(r'\midrule')
            body.append(line)
        elif line.strip().startswith(('Original &', 'Independent &')):
            r = sampling[index]
            index += 1
            identities.append([cohort, r[0], r[1]])
            body.append([r[0], comparison[r[1]], *r[2:]])
    if index != 12:
        raise ValueError('Sampling seed labels or table structure changed')
    unique(identities, (0, 1, 2), {(c, s, d) for c in (
        'GR00T / Bridge', 'SmolVLA / Spatial', 'SmolVLA / Object')
        for s in ('Original', 'Independent') for d in comparison})
    output['supp_sampling_summary.tex'] = table('llccc',
        ['Seed', 'Contrast', 'Difference [95\% CI]', 'One-sided $p$', 'Holm $p$'], body)

    destination.mkdir(parents=True, exist_ok=True)
    for name, content in output.items():
        (destination / name).write_text(content)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('destination', type=Path)
    args = parser.parse_args()
    render(args.source.resolve(), args.destination.resolve())
