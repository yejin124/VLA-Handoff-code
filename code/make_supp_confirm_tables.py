"""Detailed GR00T, image-control and additional-policy tables used by the compact supplement,
from confirmatory and robustness results (data/confirmatory/).

Usage: python code/make_supp_confirm_tables.py data/confirmatory paper/tables
"""
import argparse
import json
import sys
from pathlib import Path

CELLS = [('gr00t_bridge_confirm', 'Bridge (all)', (10, 20)), ('gr00t_bridge_confirm_new', 'Bridge (new only)', (10, 20)),
         ('gr00t_spatial_confirm', 'LIBERO-Spatial', (40, 80)), ('gr00t_object_confirm', 'LIBERO-Object', (40, 80))]
PRIMARY = {('gr00t_bridge_confirm', 20), ('gr00t_spatial_confirm', 80)}


def ci(v):
    if not v or 'ci95' not in v:
        return '--'
    lo, hi = v['ci95']
    return f"${v['estimate']:+.3f}$ [${lo:+.3f}$, ${hi:+.3f}$]"


def score(methods, name):
    value = methods.get(name, {}).get('estimate')
    return '--' if value is None else f'{value:.3f}'


def probability(cell, contrast):
    if cell.get('status', 'evaluated') != 'evaluated':
        return 1.0
    return cell.get('contrasts', {}).get(contrast, {}).get('one_sided_p', 1.0)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Default input directory for historical filenames')
    parser.add_argument('destination', type=Path)
    parser.add_argument('--confirm-results', type=Path, help='Full cohort confirm_results.json')
    parser.add_argument('--robustness-results', type=Path, help='Image-control robustness_results.json')
    parser.add_argument('--policy-results', type=Path, help='Additional-policy confirm_results.json')
    parser.add_argument('--spread-results', type=Path, help='Primary-cohort spread contrast results')
    args = parser.parse_args()
    src, out = args.source, args.destination
    confirm_path = args.confirm_results or src / 'ral_confirm_results_frozen.json'
    robustness_path = args.robustness_results or src / 'ral_robustness_results.json'
    conf = json.loads(confirm_path.read_text())['cells']
    rob = json.loads(robustness_path.read_text())['variants']['image']
    out.mkdir(parents=True, exist_ok=True)
    a = [r'% generated by code/make_supp_confirm_tables.py; do not edit', r'\begin{tabular}{@{}llccccl@{}}', r'\toprule',
         r'Cohort & Step & Scene & Scene + handoff & Spread & Scene + ext.\ + handoff vs.\ scene + ext. & $\Delta_{\mathrm{handoff}}$ [95\% CI]\\', r'\midrule']
    for key, name, steps in CELLS:
        for st in steps:
            c = conf[f'{key}|{st}']
            m, k = c['methods'], c['contrasts']
            mark = r'$^\dagger$' if (key, st) in PRIMARY else ''
            a.append(f"{name}{mark} & {st} & {score(m, 'G')} & {score(m, 'GH')} & {score(m, 'Spread')} & "
                     f"{score(m, 'GEH')} vs.\\ {score(m, 'GE')} & {ci(k.get('GH-G'))}\\\\")
    a += [r'\bottomrule', r'\end{tabular}']
    (out / 'supp_confirm_cells.tex').write_text('\n'.join(a) + '\n')
    b = [r'% generated by code/make_supp_confirm_tables.py; do not edit', r'\begin{tabular}{@{}llccl@{}}', r'\toprule',
         r'Cohort & Step & Scene + image & Scene + image + handoff & Handoff increment beyond image [95\% CI]\\', r'\midrule']
    for key, name, steps in CELLS[:1] + CELLS[2:]:
        for st in steps:
            c = rob.get(f'{key}|{st}')
            if not c:
                continue
            m, k = c.get('methods') or {}, c['contrasts'].get('GIH-GI')
            b.append(f"{name} & {st} & {('--' if m.get('GI') is None else format(m['GI'], '.3f'))} & {('--' if m.get('GIH') is None else format(m['GIH'], '.3f'))} & {ci(k)}\\\\")
    b += [r'\bottomrule', r'\end{tabular}']
    (out / 'supp_confirm_image.tex').write_text('\n'.join(b) + '\n')
    policies(src, out, policy_path=args.policy_results, spread_path=args.spread_results,
             confirm_path=confirm_path)


POLICIES = [('pi05_spatial_confirm', r'$\pi_{0.5}$', 'Spatial'), ('pi05_object_confirm', r'$\pi_{0.5}$', 'Object'),
            ('molmoact_spatial', 'MolmoAct2', 'Spatial'), ('molmoact_object', 'MolmoAct2', 'Object'),
            ('tau0_spatial', r'$\tau_0$', 'Spatial'), ('tau0_object', r'$\tau_0$', 'Object'),
            ('smolvla_spatial', 'SmolVLA', 'Spatial'), ('smolvla_object', 'SmolVLA', 'Object'),
            ('gr00t_object_confirm', 'GR00T', 'Object')]


def policies(src, out, step=80, secondary=40, *, policy_path=None, spread_path=None, confirm_path=None):
    """Per-policy LIBERO occluder cohorts: scene + handoff predictor vs. spread at the primary landmark (step 80, Holm
    over the two suites of each policy) and, below a rule, at the secondary landmark fixed in the plans (step 40,
    unadjusted one-sided p, reported whatever the direction)."""
    d = json.loads((policy_path or src / 'other_policies' / 'confirm_results.json').read_text())
    # GR00T's family also contains its Spatial cell, reported in the main table from the primary rerun
    sc = json.loads((spread_path or src / 'spread_contrast_results.json').read_text())
    spatial = sc['cells'][f'gr00t_spatial_confirm|{step}']
    family = POLICIES + [('gr00t_spatial_confirm', 'GR00T', 'Spatial')]
    holm = {}
    for contrast in ('GH-G', 'GH-Spread'):  # handoff increment beyond the scene (T2); scene + handoff predictor vs. spread (T4)
        p = {key: probability(d['cells'][f'{key}|{step}'], contrast) for key, _, _ in POLICIES}
        p['gr00t_spatial_confirm'] = probability(spatial, contrast)
        for pol in {n for _, n, _ in family}:
            keys = sorted((k for k, n, _ in family if n == pol), key=p.get)
            run = 0.0
            for i, k in enumerate(keys):
                run = max(run, min(1.0, (len(keys) - i) * p[k]))
                holm[(contrast, k)] = run
    t = [r'% generated by code/make_supp_confirm_tables.py; do not edit', r'\begin{tabular}{@{}lllccccllll@{}}', r'\toprule',
         r'Policy & Suite & Step & $N$ (fail) & Scene & Scene + handoff & Spread & $\Delta_{\mathrm{handoff}}$ [95\% CI] & $p$ & '
         r'$\Delta_{\mathrm{gap}}$ [95\% CI] & $p$\\',
         r'\midrule']
    for key, name, suite in POLICIES:
        c, co = d['cells'][f'{key}|{step}'], d['cohorts'][key]
        m = c['methods']
        n = co['landmarks'][str(step)]['active']
        f = sum(v[1] for v in co['landmarks'][str(step)]['task_counts'].values())
        cols = []
        for contrast in ('GH-G', 'GH-Spread'):
            text = ci(c['contrasts'].get(contrast))
            if holm[(contrast, key)] < 0.05:
                text = r'{\boldmath ' + text + '}'
            cols += [text, f'{holm[(contrast, key)]:.3f}' if 'one_sided_p' in c['contrasts'].get(contrast, {}) else '--']
        t.append(f"{name} & {suite} & {step} & {n} ({f}) & {score(m, 'G')} & {score(m, 'GH')} & "
                 f"{score(m, 'Spread')} & " + ' & '.join(cols) + r'\\')
    # secondary landmark: every policy, plus GR00T on Spatial from the primary rerun (its step-80 row is Table 2)
    t.append(r'\midrule')
    frozen = json.loads((confirm_path or src / 'ral_confirm_results_frozen.json').read_text())
    rows = [(key, name, suite, d['cells'][f'{key}|{secondary}'], d['cohorts'][key]) for key, name, suite in POLICIES]
    rows.append(('gr00t_spatial_confirm', 'GR00T', 'Spatial', sc['cells'][f'gr00t_spatial_confirm|{secondary}'],
                 frozen['cohorts']['gr00t_spatial_confirm']))
    for key, name, suite, c, co in rows:
        m = c['methods']
        n = co['landmarks'][str(secondary)]['active']
        f = sum(v[1] for v in co['landmarks'][str(secondary)]['task_counts'].values())
        cols = []
        for contrast in ('GH-G', 'GH-Spread'):
            pv = probability(c, contrast)
            cols += [ci(c['contrasts'].get(contrast)),
                     ('--' if 'one_sided_p' not in c['contrasts'].get(contrast, {}) else f'{pv:.4f}' if pv < 0.001 else f'{pv:.3f}')]
        t.append(f"{name} & {suite} & {secondary} & {n} ({f}) & {score(m, 'G')} & {score(m, 'GH')} & "
                 f"{score(m, 'Spread')} & " + ' & '.join(cols) + r'\\')
    t += [r'\bottomrule', r'\end{tabular}']
    (out / 'supp_confirm_policies.tex').write_text('\n'.join(t) + '\n')


if __name__ == '__main__':
    main()
