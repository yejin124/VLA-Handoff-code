"""Supplementary view-restore table from data/view_restore/view_restore_analysis.json.

The gate columns compare the successes of an alarm-gated restoration with the expected successes of a
random gate that intervenes at the same rate within each task (the JSON's random_expected_success), the
comparator used by the selective gains reported in the text.

Usage: python code/make_view_restore_table.py data/view_restore/view_restore_analysis.json paper/tables/supp_view_restore.tex
"""
import json
import sys

NAMES = {'pi05': r'$\pi_{0.5}$', 'gr00t': 'GR00T-N1.7', 'molmoact': 'MolmoAct2'}
ORDER = [('spatial', 'Spatial'), ('object', 'Object')]


def main(src, dst):
    cells = json.load(open(src))['cells']
    rows = []
    for suite, label in ORDER:
        for pol in ('pi05', 'gr00t', 'molmoact'):
            c = cells[f'{suite}|{pol}']
            gates = []
            for g in ('handoff', 'native_spread'):
                gv = c['gates'][g]
                gates.append(f"{gv['gate_success']} vs.\\ {gv['random_expected_success']:.1f} (${gv['rate']:.2f}$)")
            rows.append(f"{label} & {NAMES[pol]} & {c['n']} & {c['continue_success']} & {c['restore_success']} & "
                        f"{c['rescued']}/{c['lost']} & {gates[0]} & {gates[1]} \\\\")
    out = ['% generated by code/make_view_restore_table.py; do not edit',
           r'\begin{tabular}{llrrrrrr}', r'\toprule',
           r'Suite & Policy & $n$ & Cont. & Restore & Resc./lost & Handoff gate ($q$) & Spread gate ($q$) \\',
           r'\midrule', *rows, r'\bottomrule', r'\end{tabular}']
    open(dst, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
