"""Results figure of the Access manuscript: uncertainty registered by System 2 versus uncertainty expressed by System 1.

Inputs
  (a) frozen confirmatory results:   confirm_results.json, cells gr00t_bridge_confirm|20 and
      gr00t_spatial_confirm|80, methods G, GH, Spread (point estimate and full-refit 95% interval).
  (b) out-of-fold predictions of the frozen primary pipeline for the Bridge cell (primary_predictions.json).
  (c,d) paper/tables/probe_realistic.tex (generated by gen_realistic_tables.py), moved-goal rows:
      handoff scene-change AUROC and the paired frequency of increased spread, shown on separate axes.

Usage: python code/plot_figures.py <confirm_results.json> <primary_predictions.json> <out_dir> [regenerated_probe_realistic.tex]
"""
import json
import re
import sys
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.ticker
import numpy as np

H_COL, S_COL, G_COL, INK, MUTED = '#bf4520', '#2b6cb0', '#8a8f98', '#2d3142', '#5a6580'
ROOT = Path(__file__).resolve().parents[1]
plt.rcParams.update({'font.family': 'sans-serif', 'font.sans-serif': ['Liberation Sans', 'DejaVu Sans'],
                     'font.size': 8.5, 'axes.edgecolor': MUTED, 'axes.labelcolor': INK, 'xtick.color': MUTED,
                     'ytick.color': MUTED, 'axes.spines.top': False, 'axes.spines.right': False,
                     'axes.linewidth': 0.6, 'pdf.fonttype': 42})
POLICY = {r'$\pi_{0.5}$': 'π0.5', 'GR00T-N1.7': 'GR00T', 'MolmoAct2': 'MolmoAct2'}


def moved_goal_rows(path=None):
    rows = []
    for line in Path(path or ROOT / 'paper/tables/probe_realistic.tex').read_text().splitlines():
        cells = [c.strip() for c in line.rstrip('\\').split('&')]
        if len(cells) == 7 and cells[2] == 'Moved goal':
            # A nonsignificant decoding result can carry a TeX dagger.
            score = re.match(r"([+-]?(?:\d+(?:\.\d*)?|\.\d+))", cells[3])
            pair = re.match(r"(\d+)\s*/\s*(\d+)", cells[6])
            if score is None and not cells[3].startswith('--'):
                raise ValueError(f"Malformed moved-goal score: {line}")
            if pair is None and not cells[6].startswith('--'):
                raise ValueError(f"Malformed moved-goal pair count: {line}")
            handoff = float(score.group(1)) if score else None
            higher, count = map(int, pair.groups()) if pair else (None, None)
            if handoff is not None and not 0 <= handoff <= 1:
                raise ValueError(f"Invalid moved-goal estimate: {line}")
            if count is not None and (not 0 <= higher <= count or count <= 0):
                raise ValueError(f"Invalid moved-goal pair count: {line}")
            rows.append((cells[0], POLICY[cells[1]], handoff,
                         higher / count if count is not None else None, count))
    if len(rows) != 6:
        raise ValueError(f"Expected six policy-suite moved-goal rows, found {len(rows)}")
    return rows


def moved_goal_panels(ax_decode, ax_response, table=None):
    """Different estimands require separate axes, not a connected-point gap."""
    rows = moved_goal_rows(table)
    y = np.arange(len(rows))[::-1]
    ax_decode.scatter([np.nan if r[2] is None else r[2] for r in rows], y, s=25, color=H_COL, marker='o')
    ax_response.scatter([np.nan if r[3] is None else r[3] for r in rows], y, s=25, color=S_COL, marker='s')
    labels = [f"{pol}  {suite} (n={count if count is not None else '--'})"
              for suite, pol, _, _, count in rows]
    for row, position in zip(rows, y):
        if row[2] is None:
            ax_decode.text(.46, position, 'n/a', va='center', color=MUTED)
        if row[3] is None:
            ax_response.text(.02, position, 'n/a', va='center', color=MUTED)
    for index, ax in enumerate((ax_decode, ax_response)):
        ax.set_yticks(y, labels if index == 0 else [])
        ax.set_ylim(-0.6, len(rows) - 0.4)
        ax.axvline(0.5, color=MUTED, lw=0.6, ls=':')
    ax_decode.set_xlim(0.45, 1.0)
    ax_decode.set_xticks([.5, .6, .7, .8, .9, 1])
    ax_decode.set_xlabel('Scene-change AUROC')
    ax_decode.set_title('c  Moved goal: scene encoding', loc='left', fontsize=9, fontweight='bold', color=INK)
    ax_response.set_xlim(0.0, 1.0)
    ax_response.set_xlabel('Pairs with increased action spread\n(matched initial-state pairs)')
    ax_response.set_title('d  Moved goal: action response', loc='left', fontsize=9, fontweight='bold', color=INK)
    ax_response.xaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0, decimals=0))


def outcome_panel(ax, confirm, preds):
    cells = [('gr00t_bridge_confirm|20', 'Bridge\nstep 20'),
             ('gr00t_spatial_confirm|80', 'LIBERO-Spatial\nstep 80')]
    methods = [('G', 'Scene only', G_COL, '^'), ('GH', 'Scene + handoff', H_COL, 'o'), ('Spread', 'Action spread', S_COL, 's')]
    for ci, (key, label) in enumerate(cells):
        m = confirm['cells'][key]['methods']
        for mi, (name, mlabel, col, mk) in enumerate(methods):
            x = ci + (mi - 1) * 0.24
            est, (lo, hi) = m[name]['estimate'], m[name]['ci95']
            ax.plot([x, x], [lo, hi], color=col, lw=1.4, solid_capstyle='round')
            ax.scatter(x, est, s=24, color=col, marker=mk, zorder=3, edgecolor='white', linewidth=0.6,
                       label=mlabel if ci == 0 else None)
    ax.set_xticks([0, 1], [f'{label}\nn = {len(preds[key]["predictions"]):,}'
                           for key, label in cells], fontsize=8)
    ax.axhline(0.5, color=MUTED, lw=0.6, ls=':')
    ax.set_ylim(0.45, 1.0)
    ax.set_xlim(-0.55, 1.55)
    ax.set_ylabel('Within-task failure AUROC')
    legend = ax.legend(frameon=False, loc='upper left', fontsize=8, handletextpad=0.2, borderaxespad=0.1)
    plt.setp(legend.get_texts(), wrap=False)
    ax.set_title('a  GR00T: outcome uncertainty', loc='left', fontsize=9, fontweight='bold', color=INK)


def within_task_rank(values, tasks):
    out = np.empty(len(values))
    for t in np.unique(tasks):
        idx = np.flatnonzero(tasks == t)
        order = values[idx].argsort().argsort()
        out[idx] = (order + 0.5) / len(idx)
    return out


def quartile_panel(ax, preds):
    p = preds['gr00t_bridge_confirm|20']['predictions']
    tasks = np.array([r['task'] for r in p])
    y = np.array([r['failure'] for r in p])
    quart = {}
    for name in ('Spread', 'GH'):
        rank = within_task_rank(np.array([r['scores'][name] for r in p]), tasks)
        q = np.minimum((rank * 4).astype(int), 3)
        quart[name] = [y[q == k].mean() for k in range(4)]
    x = np.arange(1, 5)
    ax.plot(x, quart['GH'], color=H_COL, lw=2, marker='o', ms=4.5, mec='white', mew=0.6,
            label='Scene + handoff')
    ax.plot(x, quart['Spread'], color=S_COL, lw=2, marker='s', ms=4.5, mec='white', mew=0.6,
            label='Action spread')
    ax.axhline(y.mean(), color=MUTED, lw=0.6, ls=':')
    ax.text(1, y.mean() + 0.025, f'overall {100 * y.mean():.0f}%', color=MUTED, fontsize=8, va='bottom')
    legend = ax.legend(frameon=False, loc='lower right', fontsize=8, handlelength=1.6,
                       handletextpad=.5, borderaxespad=.3)
    plt.setp(legend.get_texts(), wrap=False)
    ax.set_xticks(x, ['1\nlowest', '2', '3', '4\nhighest'])
    ax.set_xlim(0.7, 4.3)
    ax.set_xlabel('Within-task score quartile')
    ax.set_ylabel('Observed failure rate')
    ax.set_ylim(0, 1.03)
    ax.set_yticks([0, .25, .5, .75, 1])
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0, decimals=0))
    ax.set_title('b  Bridge: outcomes by score', loc='left', fontsize=9, fontweight='bold', color=INK)
    return quart


def main():
    confirm = json.loads(Path(sys.argv[1]).read_text())
    preds = json.loads(Path(sys.argv[2]).read_text())
    out = Path(sys.argv[3])
    out.mkdir(parents=True, exist_ok=True)
    table = Path(sys.argv[4]) if len(sys.argv) > 4 else None
    fig, axes = plt.subplots(2, 2, figsize=(7.16, 4.35), gridspec_kw={'height_ratios': [1.15, 1]})
    outcome_panel(axes[0, 0], confirm, preds)
    low = quartile_panel(axes[0, 1], preds)
    moved_goal_panels(axes[1, 0], axes[1, 1], table)
    fig.tight_layout(w_pad=2.0, h_pad=2.1)
    fig.savefig(out / 'fig4_results.pdf', bbox_inches='tight', pad_inches=.08)
    print(json.dumps(low))


if __name__ == '__main__':
    main()
