"""Supplementary table of experiment 2 (handoff intervention) from injection_handoff_analysis.py output.

Usage: python3 code/make_handoff_injection_table.py data/injection/exp2_bridge/analysis.json paper/tables/supp_handoff_injection.tex
"""
import json
import sys

ROWS = [('risk', 'System~2 uncertainty'), ('spread', 'Spread (control)'), ('rand_mean', 'Random (mean of 4)')]


def ci(v, pct=False):
    (e, (lo, hi)), k = v, (100 if pct else 1)
    f = '{:.1f}' if pct else '{:+.3f}'
    return f"${f.format(e * k)}$ [${f.format(lo * k)}$, ${f.format(hi * k)}$]"


def main():
    d = json.load(open(sys.argv[1]))
    t = [r'% generated by code/make_handoff_injection_table.py; do not edit', r'\begin{tabular}{@{}lccc@{}}', r'\toprule',
         r'Direction & SD & $\Delta\log s$ & $\Delta_a$ (\%)\\', r'\midrule']
    for key, name in ROWS:
        for a in ('1.0', '2.0', '4.0'):
            b = d['alpha'][a]
            t.append(f"{name if a == '1.0' else ''} & {a[0]} & {ci(b['dS_' + key])} & {ci(b['dA_' + key], True)}\\\\")
    p = d['primary']
    t += [r'\midrule', f"Uncertainty $-$ random & 2 & {ci(p['D'])} & \\\\", r'\bottomrule', r'\end{tabular}']
    open(sys.argv[2], 'w').write('\n'.join(t) + '\n')


if __name__ == '__main__':
    main()
