#!/usr/bin/env python3
"""LaTeX tables for the within-condition reanalyses, from data/icassp2027/exp_20261020/*.json only.

  exp_condition.tex       E1  occluder minus moved-goal AUROC per readout and policy-suite, pooled row
  exp_effects.tex         E4  paired readout differences at step 80 with MDD, pooled post hoc rows
  exp_pooled_monitor.tex  E10 conditional vs situation-agnostic readouts (handoff, combined)
  exp_calibration.tex     E2  single-task (preregistered), pooled-9 and all-ordered-pair thresholds, step 80
  exp_visual.tex          E3  image-embedding decodability and within-situation DINOv2 AUROC, step 80

Every number is formatted once by num(), which records (printed text, source value, decimals); the
check at the end asserts that each printed number equals its JSON value rounded once.
Never hand-edit the generated files; change this script. Writes to paper/tables/.
Run: python code/gen_exp_20261020_tables.py
"""
import json
from pathlib import Path

from table_layout import note, panel, scientific_p

SRC = Path(__file__).resolve().parent.parent / "data/icassp2027/exp_20261020"
OUT = Path(__file__).resolve().parent.parent / "paper/tables"
HEADER = "% generated by code/gen_exp_20261020_tables.py from exp_20261020/{}; do not edit"
POL = {"pi05": "$\\pi_{0.5}$", "gr00t": "GR00T-N1.7", "molmoact": "MolmoAct2"}
SIT = {"occluder": "Occluder", "lighting": "Dim light", "moved": "Moved goal", "relocated": "Relocated goal"}
RD = {"native_spread": "Spread", "baseline": "External", "handoff": "Handoff", "combined": "Combined", "dinov2": "DINOv2", "resnet18": "ResNet-18"}
SUITE = {"spatial": "Spatial", "object": "Object"}
PRINTED = []


def num(x, d=2, sign=False):
    if x is None:
        return "--"
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    if float(s) == 0:
        s = f"{0:.{d}f}"   # no signed rounded zero
    PRINTED.append((s, x, d))
    return s.replace("-", "$-$") if s.startswith("-") else s


def pval(p):
    if p < 0.001:
        PRINTED.append((f"{p:.0e}", p, None))
        return scientific_p(p)
    return num(p, 3)


def ci(v):
    return f"[{num(v[0], 2, True)}, {num(v[1], 2, True)}]"


def ci3(v):
    return f"[{num(v[0], 3, True)}, {num(v[1], 3, True)}]"


def load(name):
    p = SRC / f"{name}.json"
    return json.load(open(p)) if p.exists() else None


def condition(e1):
    rows = []
    for r in e1["cells"]:
        rows.append(f"{SUITE[r['suite']]} & {POL[r['policy']]} & {RD[r['readout']]} & {num(r['mean_diff'], 2, True)} {ci(r['ci95_mean_diff'])} & "
                    f"{r['occluder_higher']}/{r['n_tasks']} & {pval(r['sign_p_two_sided'])} & {pval(r['holm_p'])}")
    pooled = []
    for m, v in e1["pooled_by_readout"].items():
        pooled.append(f"{RD[m]} & {num(v['task_cluster_mean'], 3, True)} {ci3(v['task_cluster_ci95'])} & "
                      f"{v['task_cluster_positive']}/{v['task_clusters']} & {pval(v['task_cluster_sign_p'])}")
    return "\n".join([
        panel("A. Policy-specific contrasts", "lllcccc", "Suite & Policy & Readout & Occ.$-$moved [95\\% CI] & Tasks & Sign $p$ & Holm $p$", rows),
        panel("B. Pooled contrasts (post hoc)", "lccc", "Readout & Occ.$-$moved [95\\% CI] & Positive clusters & Sign $p$", pooled),
        note("Holm adjustment in panel A covers 24 tests. Panel B averages policies within each suite--task cluster; its sign-test $p$ values are unadjusted.")])


def effects(e4):
    comps = ["handoff-native_spread", "handoff-baseline", "combined-baseline"]
    cells = {}
    for r in e4["cells"]:
        cells.setdefault((r["suite"], r["situation"], r["policy"]), {})[r["comparison"]] = r
    rows = []
    for (s, f, p), v in cells.items():
        rows.append(f"{SUITE[s]} & {SIT[f]} & {POL[p]} & " + " & ".join(
            r"\shortstack{" + f"{num(v[c]['mean_diff'], 2, True)} {ci(v[c]['ci95_mean_diff'])}" +
            r"\\(" + num(v[c]['mdd80_paired_t'], 2) + ")}" for c in comps))
    pooled_rows = []
    for scope in ("occluder", "moved"):
        pooled = {r["comparison"]: r for r in e4["pooled"] if r["situations"] == scope}
        pooled_rows.append(f"{SIT[scope]} & " + " & ".join(
            r"\shortstack{" + f"{num(pooled[c]['task_cluster_mean'], 3, True)} [{num(pooled[c]['task_cluster_ci95'][0], 3, True)}, {num(pooled[c]['task_cluster_ci95'][1], 3, True)}]" +
            r"\\(" + f"{pooled[c]['task_cluster_positive']}/{pooled[c]['task_clusters']}, Holm {pval(pooled[c]['task_cluster_holm_p'])})" + "}" for c in comps))
    return "\n".join([
        panel("A. Policy-specific effects and detectable differences", "lllccc",
              "Suite & Situation & Policy & Handoff$-$Spread (MDD) & Handoff$-$External (MDD) & Combined$-$External (MDD)", rows, fit=True),
        panel("B. Pooled effects (post hoc)", "lccc",
              "Situation & Handoff$-$Spread & Handoff$-$External & Combined$-$External", pooled_rows, fit=True),
        note("Panel A gives mean differences, 95\\% intervals and MDD in parentheses. Panel B gives equal-cluster mean differences and intervals; parentheses give positive clusters / 20 and Holm-adjusted $p$, not MDD.")])


def pooled_monitor(e10):
    rows = []
    for r in e10["cells"]:
        if r["landmark"] != 80 or r["readout"] not in ("handoff", "combined"):
            continue
        d, a = r["pooled_minus_conditional"], r["pooled_above_chance"]
        above_holm, difference_holm = r.get("pooled_above_chance_holm_p"), d.get("holm_p")
        above_suffix = "" if above_holm is None else f"; {pval(above_holm)}"
        difference_suffix = "" if difference_holm is None else f"; {pval(difference_holm)}"
        rows.append(f"{SUITE[r['suite']]} & {SIT[r['situation']]} & {POL[r['policy']]} & {RD[r['readout']]} & "
                    f"{num(r['conditional_model_median'])} & " + r"\shortstack{" + num(r['pooled_model_median']) +
                    r"\\(" + f"{a[0]}/{a[1]}; {pval(a[2])}{above_suffix})" + "} & " +
                    r"\shortstack{" + num(d['mean'], 2, True) + r"\\(" +
                    f"{d['positive']}/{r['n_tasks']}; {pval(d['sign_p'])}{difference_suffix})" + "}")
    return "\n".join([
        panel("Situation-specific versus situation-agnostic fitting", "llllccc",
              r"Suite & Situation & Policy & Readout & Specific & \shortstack{Agnostic\\(tasks $>0.5$; $p$; $p_{\rm H}$)} & \shortstack{Mean paired change\\(higher tasks; $p$; $p_{\rm H}$)}", rows, fit=True),
        note(r"$p_{\rm H}$ denotes Holm-adjusted $p$, reported for occluder and moved-goal families only; relocation tuples contain only counts and unadjusted $p$. The change is the mean paired task difference, not the difference of the displayed median AUROCs.")])


def calibration(e2):
    """Keep fitted-rule intervals separate from ordered-pair descriptive rates."""
    rules = [("single_task_rule", "Single"), ("shared_3_task_rule", "Shared-3"),
             ("pooled_9_task_rule", "Pooled-9")]
    head = ("Suite & Situation & Policy & Score & Rule & Cal.\\ succ. & FPR median [95\\% CI] & FPR Q3 [95\\% CI] & "
            "FPR max & TPR median")
    rows, pairs = [], []
    for cell in e2["cells"]:
        res = cell["landmarks"].get("80")
        if res is None:
            continue
        for m in ("native_spread", "handoff"):
            prefix = f"{SUITE[cell['suite']]} & {SIT[cell['situation']]} & {POL[cell['policy']]} & {RD[m]}"
            for key, label in rules:
                v = res[m][key]
                f, t, n = v["fpr"], v["tpr"], v.get("calibration_successes")
                if f is None:
                    continue
                if not n or t is None:
                    raise ValueError("Missing fitted-rule calibration summary")
                succ = (num(n['median'], 0) if n["min"] == n["max"] else
                        f"{num(n['median'], 0)} ({num(n['min'], 0)}--{num(n['max'], 0)})")
                def fci(q):
                    return f"{num(f[q])} [{num(f[q + '_ci95'][0])}, {num(f[q + '_ci95'][1])}]"
                rows.append(f"{prefix} & {label} & {succ} & {fci('median')} & {fci('q3')} & {num(f['max'])} & {num(t['median'])}")
            v = res[m]["all_ordered_pairs"]
            f, t = v["fpr"], v["tpr"]
            if f is not None:
                if t is None:
                    raise ValueError("Missing ordered-pair true-positive rate")
                pairs.append(f"{prefix} & {v['n_pairs']} & {num(f['median'])} & {num(f['q3'])} & {num(f['max'])} & {num(t['median'])}")
    long = [r"\begin{longtable}{@{}llllllcccc@{}}",
            r"\caption{Realized held-out operating points at step 80 (nominal FPR $0.10$). Panel A: calibration rules with task-bootstrap 95\% intervals; Single is prespecified, Shared-3 and Pooled-9 are post hoc. Cal.\ succ.: successful calibration episodes per test task, median (range). Panel B: all ordered calibration--test task pairs, post hoc.}\label{tab:cal}\\",
            r"\toprule", head + r"\\", r"\midrule", r"\endfirsthead",
            r"\multicolumn{10}{l}{\textit{Table~\ref{tab:cal}, panel A (continued)}}\\",
            r"\toprule", head + r"\\", r"\midrule", r"\endhead",
            *[r + r"\\" for r in rows], r"\bottomrule", r"\end{longtable}"]
    # This panel fits on one page and shares the table number without adding a float.
    long += [r"\noindent\begin{minipage}{\textwidth}\centering",
             panel(r"Table~\ref{tab:cal}, panel B. All ordered task pairs", "llllccccc",
                   "Suite & Situation & Policy & Score & Pairs & FPR median & FPR Q3 & FPR max & TPR median", pairs),
             note("Pairs counts valid ordered calibration--test task pairs. Calibration sample sizes vary by pair and were not summarized in this analysis. These rates are descriptive; bootstrap intervals were not computed for panel B."),
             r"\end{minipage}"]
    return "\n".join(long)


def visual(e3):
    scene, ranking, pooled = [], [], []
    camera_cells = 0
    for d in e3["decodability"]:
        for f, r in d["situations"].items():
            if f in ("occluder", "lighting"):
                camera_cells += 1
            if r.get('status') == 'not_evaluated':
                scene.append(f"{SUITE[d['suite']]} & {SIT[f]} & {POL[d['policy']]} & -- & -- & -- & -- & --")
                continue
            p = r.get("dinov2_p_phipson_smyth")
            scene.append(f"{SUITE[d['suite']]} & {SIT[f]} & {POL[d['policy']]} & {num(r['handoff_auroc'])} & {num(r['image_stats_auroc'])} & "
                         f"{num(r['dinov2_auroc'])}{'' if p is None else ' (' + pval(p) + ')'} & {num(r['resnet18_auroc'])} & {ci(r['handoff_minus_dinov2_ci95'])}")
    if camera_cells != 12:
        raise ValueError("Incomplete camera decodability cells")
    for w in e3["within_situation_step80"]:
        a, c = w["above_chance"]["dinov2"], w["comparisons"]["handoff-dinov2"]
        ranking.append(f"{SUITE[w['suite']]} & {SIT[w['situation']]} & {POL[w['policy']]} & {num(w['median_auroc']['handoff'])} & {num(w['median_auroc']['baseline'])} & "
                       f"{num(w['median_auroc']['dinov2'])} ({a[0]}/{a[1]}, {pval(a[2])}) & {num(w['median_auroc']['resnet18'])} & "
                       f"{num(c['mean_diff'], 2, True)} {ci(c['ci95'])}")
    names = {"handoff-dinov2": "Handoff$-$DINOv2", "handoff-resnet18": "Handoff$-$ResNet-18",
             "dinov2-baseline": "DINOv2$-$External", "dinov2-native_spread": "DINOv2$-$Spread"}
    for scope in ("occluder", "moved"):
        for comp, label in names.items():
            v = e3["pooled_comparisons"].get(f"{comp}|{scope}")
            if not v:
                pooled.append(f"{SIT[scope]} & {label} & -- & -- & -- & --")
                continue
            pooled.append(f"{SIT[scope]} & {label} & {num(v['task_cluster_mean'], 3, True)} "
                          f"[{num(v['task_cluster_ci95'][0], 3, True)}, {num(v['task_cluster_ci95'][1], 3, True)}] & "
                          f"{v['task_cluster_positive']}/{v['task_clusters']} & {pval(v['task_cluster_sign_p'])} & {pval(v['task_cluster_holm_p'])}")
    return "\n".join([
        panel("A. Scene decodability", "lllccccc", "Suite & Situation & Policy & Handoff & Image stats & DINOv2 ($p$) & ResNet-18 & Handoff$-$DINOv2 [95\\% CI]", scene, fit=True),
        note("Camera and goal rows retain the estimates from the supplied analysis, including non-ceiling camera results. DINOv2 $p$ values test matched-pair scene decodability."),
        panel("B. Within-situation failure ranking at step 80", "lllccccc", "Suite & Situation & Policy & Handoff & External & DINOv2 (tasks, $p$) & ResNet-18 & Handoff$-$DINOv2 [95\\% CI]", ranking, fit=True),
        panel("C. Pooled failure-ranking contrasts (post hoc)", "llcccc", "Situation & Contrast & Mean [95\\% CI] & Positive clusters & Sign $p$ & Holm $p$", pooled, fit=True),
        note("Panel B reports median task AUROCs and mean paired task differences; DINOv2 tuples give tasks above 0.5 and a one-sided sign-test $p$. Panel C averages policies within suite--task clusters and reports two-sided sign tests.")])


def check():
    """Each printed number is its source value rounded once."""
    assert PRINTED, "nothing printed"
    for text, value, d in PRINTED:
        if d is None:
            assert abs(float(text) - value) <= 0.5 * 10 ** (int(f"{value:.0e}".split("e")[1])), (text, value)
        else:
            assert float(text) == round(value, d) or text == f"{value:+.{d}f}", (text, value, d)
            assert abs(float(text) - value) <= 0.5 * 10 ** -d + 1e-12, (text, value, d)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    jobs = [("exp_condition", "e1_condition", condition), ("exp_effects", "e4_effects", effects),
            ("exp_pooled_monitor", "e10_pooled_monitor", pooled_monitor), ("exp_calibration", "e2_calibration", calibration),
            ("exp_visual", "e3_image_embedding", visual)]
    for out, src, fn in jobs:
        data = load(src)
        if data is None:
            print(f"skip {out}: {src}.json missing")
            continue
        commit = data["provenance"]["git_commit"][:7]
        (OUT / f"{out}.tex").write_text(HEADER.format(f"{src}.json (analysis commit {commit})") + "\n" + fn(data) + "\n")
        print(f"wrote {out}.tex")
    check()
    print(f"check passed: {len(PRINTED)} numbers")


if __name__ == "__main__":
    main()
